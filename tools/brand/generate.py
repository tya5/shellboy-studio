#!/usr/bin/env python3
"""Approved e0b6271 geometry, new accent palette. resvg-py==0.5.0; no network.

Run python3 tools/brand/generate.py [--check]. Check rerenders all bytes, including
ICO directory offsets and its exact 16/32/48 PNG payloads, without writing.
"""
import argparse
import importlib.metadata
import json
from pathlib import Path
import struct
import xml.etree.ElementTree as ET
import resvg_py

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "web/app/public/brand"
GEOMETRY = json.loads(Path(__file__).with_name("geometry.json").read_text())
COLORS = {"tile": "#0369a1", "face": "#000810", "bubble": "#FEF2D1", "wink": "#0369a1", "eye": "#FEF2D1"}
ROLES = ["tile", "face", "bubble", "wink", "eye"]


def svg(size, adaptive=False):
    root = ET.Element("svg", {"xmlns": "http://www.w3.org/2000/svg", "width": str(size if size != "master" else 390), "height": str(size if size != "master" else 390), "viewBox": "0 0 390 390"})
    if adaptive:
        ET.SubElement(root, "style").text = ".tile{fill:#0369a1}.wink{stroke:#0369a1}@media(prefers-color-scheme:dark){.tile{fill:#38bdf8}.wink{stroke:#38bdf8}}"
    for role, shape in zip(ROLES, GEOMETRY[str(size)]):
        attributes = dict(shape["attributes"])
        attributes["class"] = role
        attributes["fill"] = "none" if role == "wink" else COLORS[role]
        if role == "wink":
            attributes["stroke"] = COLORS[role]
        ET.SubElement(root, shape["tag"], attributes)
    return ET.tostring(root, encoding="utf-8", xml_declaration=True)


def outputs():
    if importlib.metadata.version("resvg-py") != "0.5.0":
        raise RuntimeError("Use already provisioned resvg-py==0.5.0; do not silently change renderer")
    files = {f"studio-teal-{size}.svg": svg(size) for size in ["master", 16, 32]}
    files["studio-favicon.svg"] = svg(16, adaptive=True)
    for size in [16, 32, 48, 180, 192, 512]:
        source = files[f"studio-teal-{size if size in (16, 32) else 'master'}.svg"]
        files[f"studio-teal-{size}.png"] = resvg_py.svg_to_bytes(svg_string=source.decode(), width=size, height=size)
    payloads = [files[f"studio-teal-{size}.png"] for size in [16, 32, 48]]
    offset = 6 + 16 * len(payloads)
    entries = b""
    for size, payload in zip([16, 32, 48], payloads):
        entries += struct.pack("<BBBBHHII", size, size, 0, 0, 1, 32, len(payload), offset)
        offset += len(payload)
    files["studio-teal.ico"] = struct.pack("<HHH", 0, 1, len(payloads)) + entries + b"".join(payloads)
    return files


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for name, data in outputs().items():
        path = OUT / name
        if args.check:
            if path.read_bytes() != data:
                raise SystemExit(f"generated bytes differ: {name}")
        else:
            path.write_bytes(data)
    print("11 SVG/PNG/ICO artifacts match deterministic generation" if args.check else "generated 11 approved-shape artifacts")
